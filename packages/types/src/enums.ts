/**
 * Domain enums shared across backend and frontend.
 * Keep values stable — they are persisted in the database and serialized over the API.
 */

export enum UserRole {
  /** Site owner / super admin. Full access. */
  ADMIN = 'admin',
  /** A photographer who owns photos, albums and collections. */
  PHOTOGRAPHER = 'photographer',
  /** A regular authenticated visitor (can like, bookmark, comment). */
  USER = 'user',
}

export enum AuthProvider {
  LOCAL = 'local',
  GOOGLE = 'google',
}

/** Lifecycle status for publishable content (photos, albums, collections). */
export enum ContentStatus {
  DRAFT = 'draft',
  PUBLISHED = 'published',
  ARCHIVED = 'archived',
}

/** Image derivatives generated by the upload pipeline. */
export enum ImageVariant {
  ORIGINAL = 'original',
  THUMBNAIL = 'thumbnail',
  WEBP = 'webp',
  AVIF = 'avif',
}

export enum CommentStatus {
  VISIBLE = 'visible',
  HIDDEN = 'hidden',
  FLAGGED = 'flagged',
}

export enum SortOrder {
  ASC = 'ASC',
  DESC = 'DESC',
}
