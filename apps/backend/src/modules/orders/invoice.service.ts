import { Injectable } from '@nestjs/common';
import { ConfigService } from '@nestjs/config';
import PDFDocument from 'pdfkit';
import type { Order } from './entities/order.entity';

const money = (cents: number, currency: string) =>
  `${currency.toUpperCase()} ${(cents / 100).toFixed(2)}`;

/** Renders a downloadable PDF invoice for a paid order using pdfkit. */
@Injectable()
export class InvoiceService {
  private readonly siteName: string;

  constructor(configService: ConfigService) {
    this.siteName = configService.get<string>('APP_NAME') ?? 'Aperture';
  }

  /** Build the invoice PDF as a Buffer (so it can be streamed or emailed). */
  generate(order: Order): Promise<Buffer> {
    return new Promise((resolve, reject) => {
      const doc = new PDFDocument({ size: 'A4', margin: 50 });
      const chunks: Buffer[] = [];
      doc.on('data', (c: Buffer) => chunks.push(c));
      doc.on('end', () => resolve(Buffer.concat(chunks)));
      doc.on('error', reject);

      // Header
      doc.fontSize(22).text(this.siteName, { continued: false });
      doc.fontSize(10).fillColor('#666').text('Invoice', { align: 'right' });
      doc.moveDown();

      doc.fillColor('#000').fontSize(12);
      doc.text(`Invoice: ${order.invoiceNumber}`);
      doc.text(`Status: ${order.status}`);
      doc.text(`Billed to: ${order.billingEmail}`);
      doc.text(`Date: ${(order.paidAt ?? order.createdAt).toISOString().slice(0, 10)}`);
      doc.moveDown();

      // Line items
      doc.fontSize(13).text('Items', { underline: true });
      doc.moveDown(0.5);
      doc.fontSize(11);
      for (const item of order.items ?? []) {
        doc.text(`${item.albumTitle} — ${item.pricingName} (${item.licenseType})`, {
          continued: true,
        });
        doc.text(money(item.unitPriceCents, order.currency), { align: 'right' });
      }
      doc.moveDown();

      // Totals
      const row = (label: string, value: string) => {
        doc.text(label, { continued: true });
        doc.text(value, { align: 'right' });
      };
      doc.fontSize(11);
      row('Subtotal', money(order.subtotalCents, order.currency));
      if (order.discountCents)
        row('Album discount', `- ${money(order.discountCents, order.currency)}`);
      if (order.couponCents)
        row(
          `Coupon ${order.couponCode ?? ''}`.trim(),
          `- ${money(order.couponCents, order.currency)}`,
        );
      row('Tax', money(order.taxCents, order.currency));
      doc.fontSize(13);
      row('Total', money(order.totalCents, order.currency));
      if (order.refundedCents) {
        doc.fontSize(11).fillColor('#b00');
        row('Refunded', `- ${money(order.refundedCents, order.currency)}`);
        doc.fillColor('#000');
      }

      doc.moveDown(2);
      doc
        .fontSize(9)
        .fillColor('#888')
        .text(`Thank you for your purchase. This invoice was generated by ${this.siteName}.`, {
          align: 'center',
        });

      doc.end();
    });
  }
}
